#!/usr/bin/env node
/* Behavioral contract checks for the actual German Coach storage code.
   Uses a simulated localStorage; does not claim live browser certification. */
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {dirname,join} from "node:path";
import {fileURLToPath} from "node:url";
import vm from "node:vm";
const root=join(dirname(fileURLToPath(import.meta.url)),"..");
const html=readFileSync(join(root,"apps/German_coach_index.html"),"utf8");
const source=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(source,"Coach script is present");
const first=source.indexOf("function coachLearnerId()");
const last=source.indexOf("let completed",first);
assert.ok(first>=0&&last>first,"Coach storage adapter found");
const adapter=source.slice(first,last);
const data=new Map();
let active="";
const store={getItem:k=>k==="german_active_learner"?active:(data.has(k)?data.get(k):null),setItem:(k,v)=>{if(k==="german_active_learner")active=String(v);else data.set(k,String(v))},removeItem:k=>data.delete(k)};
const context={localStorage:store,Array,JSON};
vm.createContext(context);
vm.runInContext(adapter+";globalThis.contract={coachKey,coachLearnerId,storage};",context);
const {coachKey,storage}=context.contract;
active="Ava";
const avaKey=coachKey("gt_trav_completed");storage.save("gt_trav_completed",[1,2]);storage.save("gt_trav_quizHistory",[{day:2,score:90}]);
active="Ben";const benKey=coachKey("gt_trav_completed");
assert.notEqual(avaKey,benKey,"Different learners must use different keys");
assert.equal(storage.load("gt_trav_completed",[]).length,0,"New learner begins empty");
storage.save("gt_trav_completed",[1]);storage.save("gt_trav_quizHistory",[{day:1,score:80}]);
assert.equal(storage.load("gt_trav_quizHistory",[])[0].score,80);
store.removeItem(coachKey("gt_trav_completed"));
assert.equal(storage.load("gt_trav_completed",[]).length,0,"Reset only selected learner");
active="Ava";
assert.deepEqual(Array.from(storage.load("gt_trav_completed",[])),[1,2],"Ava completion survives Ben reset");
assert.equal(storage.load("gt_trav_quizHistory",[])[0].score,90,"Ava quiz history survives");
active="";
store.setItem("gt_trav_completed",JSON.stringify([5,6]));
assert.equal(coachKey("gt_trav_completed"),"gt_trav_completed","Anonymous mode preserves original legacy key");
assert.deepEqual(Array.from(storage.load("gt_trav_completed",[])),[5,6],"Legacy progress still readable");
active="Ava";
assert.deepEqual(Array.from(storage.load("gt_trav_completed",[])),[1,2],"Legacy history does not leak into named record");
assert.ok(source.includes("localStorage.removeItem(coachKey('gt_trav_completed'))"),"Coach reset uses scoped key");
assert.ok(source.includes("location.reload()"),"Learner switch reloads cached coach state");
const validatorStart=source.indexOf("function validateCoachImport(input)");
const validatorEnd=source.indexOf("async function previewCoachImport()",validatorStart);
assert.ok(validatorStart>=0&&validatorEnd>validatorStart,"Import validator exists");
vm.runInContext(source.slice(validatorStart,validatorEnd)+";globalThis.validatePortfolio=validateCoachImport;",context);
const validate=context.validatePortfolio;
const valid={format:"khaemenes-german-coach-v2",version:2,learnerRecord:"61-76-61",completed:[1,2],notes:{},quizHistory:[],examHistory:[],currentDay:2,passThreshold:70,autoSpeak:false};
assert.equal(validate(valid).source,"61-76-61");
assert.throws(()=>validate({...valid,format:"unknown"}),/Unsupported file format/);
assert.throws(()=>validate({...valid,completed:[0]}),/Invalid completed lessons/);
assert.throws(()=>validate({...valid,examHistory:"broken"}),/Invalid examHistory/);
assert.throws(()=>validate({...valid,passThreshold:900}),/Invalid settings/);
assert.throws(()=>validate({...valid,notes:[]}),/Invalid notes/);
assert.throws(()=>validate({...valid,completed:[1,1]}),/Duplicate completed lessons/);
assert.throws(()=>validate({...valid,notes:{"366":"bad"}}),/Invalid lesson note/);
assert.throws(()=>validate({...valid,notes:{"1":33}}),/Invalid lesson note/);
assert.throws(()=>validate({...valid,quizHistory:[null]}),/Invalid quizHistory entry/);
assert.throws(()=>validate({...valid,examHistory:[false]}),/Invalid examHistory entry/);

assert.ok(source.includes("data.source!==target"),"Import must block mismatched learner");
assert.ok(source.includes('confirm("Replace all German Coach progress'),"Import requires explicit replacement confirmation");
const txStart=source.indexOf("function replaceCoachPortfolioSafely(values)");
const txEnd=source.indexOf("function confirmCoachImport()",txStart);
assert.ok(txStart>=0&&txEnd>txStart,"Transactional import helper exists");
vm.runInContext(source.slice(txStart,txEnd)+";globalThis.transaction=replaceCoachPortfolioSafely;",context);
const transaction=context.transaction;
active="Ava";
const fields=["completed","notes","quizHistory","examHistory","currentDay","passThreshold","autoSpeak"];
const imported={completed:[10],notes:{},quizHistory:[],examHistory:[],currentDay:10,passThreshold:80,autoSpeak:true};
const initial=fields.map(field=>store.getItem(coachKey("gt_trav_"+field)));
const outcome=transaction(imported);
assert.equal(outcome.ok,true,"Valid replacement succeeds");
assert.deepEqual(Array.from(storage.load("gt_trav_completed",[])),[10]);
for(let i=0;i<fields.length;i++){if(initial[i]===null)store.removeItem(coachKey("gt_trav_"+fields[i]));else store.setItem(coachKey("gt_trav_"+fields[i]),initial[i])}
let writes=0;
const baseSet=store.setItem;
store.setItem=(key,val)=>{if(++writes===4)throw Error("simulated quota");baseSet(key,val)};
const failure=transaction(imported);
store.setItem=baseSet;
assert.equal(failure.ok,false);
assert.equal(failure.rollbackFailed,false,"Prior records restored after a failed import");
for(let i=0;i<fields.length;i++)assert.equal(store.getItem(coachKey("gt_trav_"+fields[i])),initial[i],"Original value restored: "+fields[i]);
console.log("GERMAN_COACH_ISOLATION=PASS: two learners, quiz separation, scoped reset, unchanged legacy records");
